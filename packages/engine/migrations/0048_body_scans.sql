CREATE TABLE body_scans (
  user_id INTEGER NOT NULL REFERENCES users (id),
  id INTEGER PRIMARY KEY,
  day TEXT NOT NULL CHECK (date(day, '+0 days') IS day),
  method TEXT NOT NULL CHECK (method IN ('dexa')),
  total_mass_kg REAL NOT NULL CHECK (total_mass_kg > 0),
  body_fat_pct REAL NOT NULL CHECK (body_fat_pct BETWEEN 0 AND 100),
  fat_mass_kg REAL NOT NULL CHECK (fat_mass_kg >= 0),
  lean_mass_kg REAL NOT NULL CHECK (lean_mass_kg >= 0),
  bone_mineral_kg REAL NOT NULL CHECK (bone_mineral_kg >= 0),
  arms_fat_pct REAL CHECK (arms_fat_pct BETWEEN 0 AND 100),
  arms_lean_kg REAL CHECK (arms_lean_kg >= 0),
  legs_fat_pct REAL CHECK (legs_fat_pct BETWEEN 0 AND 100),
  legs_lean_kg REAL CHECK (legs_lean_kg >= 0),
  trunk_fat_pct REAL CHECK (trunk_fat_pct BETWEEN 0 AND 100),
  trunk_lean_kg REAL CHECK (trunk_lean_kg >= 0),
  android_fat_pct REAL CHECK (android_fat_pct BETWEEN 0 AND 100),
  android_lean_kg REAL CHECK (android_lean_kg >= 0),
  gynoid_fat_pct REAL CHECK (gynoid_fat_pct BETWEEN 0 AND 100),
  gynoid_lean_kg REAL CHECK (gynoid_lean_kg >= 0),
  bone_density_g_cm2 REAL CHECK (bone_density_g_cm2 > 0),
  t_score REAL CHECK (t_score BETWEEN -10 AND 10),
  note TEXT CHECK (instr(note, char(0)) = 0 AND length(note) <= 500),
  created_at TEXT NOT NULL CHECK (strftime('%Y-%m-%dT%H:%M:%fZ', created_at, '+0 seconds') IS created_at),
  UNIQUE (user_id, day, method)
) STRICT;
